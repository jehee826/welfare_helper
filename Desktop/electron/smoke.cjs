const assert = require("node:assert/strict");
module.exports = async ({ panel, overlay, guide, collapse, showPanel, hidePanel, getStage, getState, blocked }) => {
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  assert.equal(panel.isVisible(), true);
  assert.equal(panel.isAlwaysOnTop(), true);
  assert.equal(overlay.isFocusable(), false);
  assert.equal(overlay.isVisible(), false);
  assert.equal(await panel.webContents.executeJavaScript("typeof require"), "undefined");
  collapse(); assert.equal(panel.getBounds().height, 76);
  collapse(); assert.equal(getState().collapsed, false);
  const guidance = guide();
  assert.equal(getState().status, "waiting");
  await guidance;
  getStage().focus();
  await wait(150);
  assert.equal(getState().status, "guide");
  assert.equal(getStage().isVisible(), true);
  const visible = getState().visibility === "visible";
  assert.equal(overlay.isVisible(), visible);
  assert.match(await panel.webContents.executeJavaScript("document.querySelector('.status').textContent"), /안내/);
  // 표시·좌표 갱신을 확인한다. OS 수준 클릭 통과와 포커스 이동은 수동 확인 대상이다.
  const oldX = overlay.getBounds().x;
  getStage().setPosition(getStage().getBounds().x + 20, getStage().getBounds().y);
  await wait(120);
  if (visible && getState().visibility === "visible") assert.equal(overlay.getBounds().x, oldX + 20);
  await getStage().webContents.executeJavaScript("document.getElementById('practice-target').click()");
  await wait(100);
  assert.equal(getState().status, "done");
  assert.equal(overlay.isVisible(), false);
  assert.match(await getStage().webContents.executeJavaScript("document.getElementById('click-count').textContent"), /1회/);
  await panel.webContents.executeJavaScript("window.desktop.command('error')");
  await wait(80);
  assert.equal(getState().status, "error");
  assert.match(await panel.webContents.executeJavaScript("document.querySelector('.error').textContent"), /로컬 오류 시연/);
  panel.close(); assert.equal(panel.isVisible(), false); assert.equal(panel.isDestroyed(), false);
  showPanel(); assert.equal(panel.isVisible(), true);
  hidePanel(); assert.equal(panel.isVisible(), false);
  assert.equal(blocked(), 0);
  console.log("DESKTOP_SMOKE_PASS: 접기/안내/좌표/연습버튼/오류/닫기숨김/재열기; 외부요청 0");
};
